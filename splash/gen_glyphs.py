#!/usr/bin/env python3
"""Rasterise the few glyphs the splash needs into 2-bit coverage, run-length coded, as a C header.

Inter is licensed under the SIL Open Font License 1.1; the rasterised subset carries that licence."""
import os
from PIL import Image, ImageDraw, ImageFont

# Static Inter instances are made from the variable font the site already ships.
SRC = os.path.join(os.path.dirname(__file__), "..", "assets", "fonts", "inter-latin-opsz-normal.woff2")
for weight, name, opsz in [(100, "thin", 32), (400, "regular", 14), (600, "semibold", 14)]:
    if not os.path.exists(f"inter-{name}.ttf"):
        from fontTools.ttLib import TTFont
        from fontTools.varLib import instancer
        inst = instancer.instantiateVariableFont(TTFont(SRC), {"wght": weight, "opsz": opsz})
        inst.flavor = None
        inst.save(f"inter-{name}.ttf")

STRINGS_REGULAR = [
    "firmware · root of trust", "bootloader · measured image", "seL4 microkernel · MCS",
    "static system description", "safety controller", "capability broker", "agents",
    "a verified foundation for agents", "the agent proposes. the loop disposes.",
]
STRINGS_SEMIBOLD = ["zOS", "assumed", "proven", "tested", "untrusted"]
STRINGS_THIN = ["zOS"]

FONTS = [  # name, file, pixel size, strings
    ("regular", "inter-regular.ttf", 13, STRINGS_REGULAR),
    ("semibold", "inter-semibold.ttf", 13, STRINGS_SEMIBOLD),
    ("thin", "inter-thin.ttf", 72, STRINGS_THIN),
]


def rle(levels):
    """One byte per run: value in the top two bits, run length - 1 in the low six."""
    out, i = [], 0
    while i < len(levels):
        v, n = levels[i], 1
        while i + n < len(levels) and levels[i + n] == v and n < 64:
            n += 1
        out.append((v << 6) | (n - 1))
        i += n
    return out


lines = ["/* generated by gen_glyphs.py - Inter (SIL OFL 1.1), 2-bit coverage, run-length coded */",
         "#include <stdint.h>"]
total = 0
for name, path, size, strings in FONTS:
    font = ImageFont.truetype(path, size)
    chars = sorted(set("".join(strings)))
    ascent, descent = font.getmetrics()
    height = ascent + descent
    data, table = [], []
    for ch in chars:
        adv = round(font.getlength(ch))
        box = font.getbbox(ch)
        left = min(0, box[0])
        w = max(adv, box[2]) - left
        img = Image.new("L", (max(w, 1), height), 0)
        ImageDraw.Draw(img).text((-left, 0), ch, font=font, fill=255)
        levels = [round(p * 3 / 255) for p in img.tobytes()]
        table.append((ord(ch), img.width, adv, left, len(data)))
        data += rle(levels)
    total += len(data) + 6 * len(table)
    lines.append(f"static const uint8_t {name}_data[{len(data)}] = {{" + ",".join(map(str, data)) + "};")
    lines.append(f"static const struct glyph {name}_glyphs[{len(table)}] = {{" +
                 ",".join(f"{{{c},{w},{a},{l},{o}}}" for c, w, a, l, o in table) + "};")
    lines.append(f"static const struct font font_{name} = {{{height},{len(table)},{name}_glyphs,{name}_data}};")
open("glyphs.h", "w").write("\n".join(lines) + "\n")
print("glyph bytes (data + table):", total)

"""Emit the SHA-256 constants of FIPS 180-4 as a C header, computed rather than typed.

K[i] = first 32 bits of the fractional part of the cube root of the i-th prime (i < 64),
H0[i] = the same for the square root of the i-th prime (i < 8). Exact integer arithmetic."""
from math import isqrt


def icbrt(n):
    lo, hi = 0, 1 << (n.bit_length() // 3 + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** 3 <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


primes, n = [], 2
while len(primes) < 64:
    if all(n % p for p in primes):
        primes.append(n)
    n += 1

K = [icbrt(p << 96) & 0xFFFFFFFF for p in primes]
H = [isqrt(p << 64) & 0xFFFFFFFF for p in primes[:8]]
rows = lambda xs: ",\n".join("    " + ",".join(f"0x{v:08x}" for v in xs[i:i + 4]) for i in range(0, len(xs), 4))
with open("sha256_tables.h", "w") as f:
    f.write("/* SPDX-License-Identifier: BSD-2-Clause */\n/* generated by gen_sha_tables.py (FIPS 180-4 constants) */\n")
    f.write("static const uint32_t sha_k[64] = {\n" + rows(K) + "\n};\n")
    f.write("static const uint32_t sha_h0[8] = {\n" + rows(H) + "\n};\n")
